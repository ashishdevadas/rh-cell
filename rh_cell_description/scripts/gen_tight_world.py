#!/usr/bin/env python3
# Usage (from the repo root):
#   python3 rh_cell_description/scripts/gen_tight_world.py rh_cell_description/worlds/rh_cell.sdf rh_cell_description/worlds/rh_cell_tight.sdf 1.0
#   python3 rh_cell_description/scripts/gen_tight_world.py rh_cell_description/worlds/rh_cell.sdf rh_cell_description/worlds/rh_cell_tight_mu03.sdf 0.3
# Third argument: friction coefficient of the wall and chamfer surfaces (default 1.0 = SDF default).
# DART takes the smaller coefficient of the two surfaces in contact, and the cassette keeps the
# default 1.0, so this value is the effective cassette-wall friction. With a 45 deg chamfer the
# cassette can only slide in if mu < tan(45 deg) = 1 (see rh_cell_core chamfer_demo).
# Generate rh_cell_tight.sdf from rh_cell.sdf: 74 mm port (2 mm clearance per side) with a 5 mm x 45 deg
# lead-in chamfer on the robot side. Wall built from boxes: front layer (5 mm, 84 mm opening),
# back layer (15 mm, 74 mm opening), 4 boxes rotated 45 deg forming the chamfer faces.
import math, re, sys
src = open(sys.argv[1]).read()
MU = float(sys.argv[3]) if len(sys.argv) > 3 else 1.0
X0, X1 = 0.59, 0.61          # wall faces
YC, ZC = -0.25, 0.35         # port centre
YMIN, YMAX, ZMIN, ZMAX = -0.55, 0.05, 0.10, 0.60
H = 0.037                    # half opening (74 mm)
C = 0.005                    # chamfer
XF = X0 + C                  # end of chamfer layer
mat = '<material><diffuse>0.6 0.6 0.65 1</diffuse></material>'
cmat = '<material><ambient>0.75 0.55 0.2 1</ambient><diffuse>0.75 0.55 0.2 1</diffuse></material>'

def box(name, cx, cy, cz, sx, sy, sz, roll=0.0, pitch=0.0, yaw=0.0, m=mat):
    g = f'<geometry><box><size>{sx:.4f} {sy:.4f} {sz:.4f}</size></box></geometry>'
    surf = f'<surface><friction><ode><mu>{MU}</mu><mu2>{MU}</mu2></ode></friction></surface>'
    return (f'    <model name="{name}"><static>true</static>'
            f'<pose>{cx:.5f} {cy:.5f} {cz:.5f} {roll:.6f} {pitch:.6f} {yaw:.6f}</pose>\n'
            f'      <link name="link"><collision name="c">{g}{surf}</collision><visual name="v">{g}{m}</visual></link></model>\n')

def ring(prefix, xa, xb, h):
    """4 boxes around a square opening of half-size h, between x = xa and xb."""
    t, cx = xb - xa, (xa + xb) / 2
    ylo, yhi = YC - h, YC + h
    zlo, zhi = ZC - h, ZC + h
    out = box(f'{prefix}_ymin', cx, (YMIN + ylo) / 2, (ZMIN + ZMAX) / 2, t, ylo - YMIN, ZMAX - ZMIN)
    out += box(f'{prefix}_ymax', cx, (yhi + YMAX) / 2, (ZMIN + ZMAX) / 2, t, YMAX - yhi, ZMAX - ZMIN)
    out += box(f'{prefix}_zmin', cx, YC, (ZMIN + zlo) / 2, t, 2 * h, zlo - ZMIN)
    out += box(f'{prefix}_zmax', cx, YC, (zhi + ZMAX) / 2, t, 2 * h, ZMAX - zhi)
    return out

def chamfers():
    a = C * math.sqrt(2)            # bevel face width = side of the square cross-section
    L = 2 * (H + C)                 # length along the edge (covers the corners)
    out = ''
    for sgn in (+1, -1):
        # edge along z at y = YC + sgn*H. Bevel from (X0, YC+sgn*(H+C)) to (XF, YC+sgn*H);
        # square cross-section on the material side: centre = bevel midpoint + normal * a/2
        mx, my = (X0 + XF) / 2, YC + sgn * (H + C / 2)
        nx, ny = 1 / math.sqrt(2), sgn / math.sqrt(2)
        out += box(f'chamfer_y{"p" if sgn > 0 else "m"}', mx + nx * a / 2, my + ny * a / 2, ZC,
                   a, a, L, yaw=math.pi / 4, m=cmat)
        # edge along y at z = ZC + sgn*H (same in the x-z plane; rotation about y)
        mz = ZC + sgn * (H + C / 2)
        out += box(f'chamfer_z{"p" if sgn > 0 else "m"}', mx + nx * a / 2, YC, mz + ny * a / 2,
                   a, L, a, pitch=math.pi / 4, m=cmat)
    return out

walls = ('    <!-- Wall at x = 0.60 m, 20 mm thick, TIGHT port: 74 x 74 mm opening (2 mm clearance per side for the\n'
         '         70 mm cassette) with a 5 mm x 45 deg lead-in chamfer on the robot side (orange), so the opening is\n'
         '         84 mm at the front face. Generated by scripts/gen_tight_world.py: front layer 5 mm with an 84 mm opening,\n'
         '         back layer 15 mm with a 74 mm opening, 4 boxes rotated 45 deg forming the chamfer faces.\n'
         f'         Wall / chamfer friction coefficient mu = {MU}. -->\n'
         + ring('wall_front', X0, XF, H + C) + ring('wall_back', XF, X1, H) + chamfers())
pat = re.compile(r'    <!-- Wall at x = 0\.60 m.*?(?=    <!-- Seat)', re.S)
assert len(pat.findall(src)) == 1
out = pat.sub(lambda m: walls + '\n', src)
open(sys.argv[2], 'w').write(out)
print('written', sys.argv[2])
